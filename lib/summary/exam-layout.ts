/** Langue d'une épreuve : la sienne, sinon (épreuve ancienne) celle de l'interface. */
export function examLanguage(
  exam: GeneratedExam,
  fallback: ExamLanguage,
): ExamLanguage {
  return exam.language ?? fallback;
}

export function examDocLabels(language: ExamLanguage): ExamDocLabels {
  return LABELS[language];
}

export function localizeExamTypeFor(
  examType: string,
  labels: ExamDocLabels,
): string {
  return labels.examTypes[examType] ?? examType;
}

/** « A », « B »… pour la n-ième partie (index 0). */
export function partLetter(index: number): string {
  return String.fromCharCode(65 + (index % 26));
}

/** Lettre de sous-question : « a », « b »… */
export function subQuestionLetter(index: number): string {
  return String.fromCharCode(97 + (index % 26));
}

// « PARTIE 1 : QCM », « Partie A - … », « Part B: … », « A. … », « II — … »
const PART_PREFIX =
  /^\s*(?:(?:partie|part|section)\s*(?:[A-Z]|\d{1,2}|[IVX]+)\b\s*[:.\-–—]?\s*|(?:[A-D]|[IVX]+|\d{1,2})\s*[:.)\-–—]\s+)/i;

/** Titre de partie sans préfixe « PARTIE 1 : » recopié (épreuves anciennes / IA). */
export function cleanPartTitle(title: string): string {
  const cleaned = title.replace(PART_PREFIX, "").trim();
  return cleaned || title.trim();
}

// « A.1 », « A.1. », « 1. », « 1) », « Question 3 : »
const QUESTION_PREFIX =
  /^\s*(?:(?:question|exercice|exercise)\s*\d{1,2}\s*[:.\-–—]?\s*|[A-Z]\s*\.\s*\d{1,2}\s*[.):\-–—]?\s+|\d{1,2}\s*[.)]\s+)/i;

/** Énoncé sans numéro recopié par l'IA (la numérotation est affichée à part). */
export function cleanQuestionPrompt(prompt: string): string {
  const cleaned = prompt.replace(QUESTION_PREFIX, "").trim();
  return cleaned || prompt.trim();
}

// « a) », « b. », « 1) », « - »
const SUB_PREFIX = /^\s*(?:[a-z]\s*[).]\s+|\d{1,2}\s*[).]\s+|[-•]\s+)/;

export function cleanSubQuestion(text: string): string {
  const cleaned = text.replace(SUB_PREFIX, "").trim();
  return cleaned || text.trim();
}

export interface LaidOutDocument extends ExamDocument {
  /** Numéro continu sur toute l'épreuve. */
  number: number;
}

export interface LaidOutQuestion {
  /** « A.1 ». */
  label: string;
  question: ExamQuestion;
  prompt: string;
  subQuestions: string[];
  /** Lignes d'espace réponse à dessiner (0 = aucune). */
  answerLines: number;
}

export interface LaidOutPart {
  letter: string;
  title: string;
  points: number;
  instructions?: string;
  documents: LaidOutDocument[];
  questions: LaidOutQuestion[];
}

/**
 * Espace réponse : celui demandé par l'IA (borné), sinon — épreuves plus
 * anciennes — aucun, comme leur affichage d'origine.
 */
function answerLinesFor(question: ExamQuestion): number {
  if (question.kind !== "open") return 0;
  const requested = question.answerLines ?? 0;
  return Math.max(0, Math.min(20, Math.round(requested)));
}

export function layoutExam(exam: GeneratedExam): LaidOutPart[] {
  let documentNumber = 0;
  return exam.parts.map((part: ExamPart, partIndex) => {
    const letter = partLetter(partIndex);
    return {
      letter,
      title: cleanPartTitle(part.title),
      points: part.points,
      instructions: part.instructions?.trim() || undefined,
      documents: (part.documents ?? [])
        .filter((doc) => doc.content?.trim() || doc.table?.rows.length)
        .map((doc) => ({ ...doc, number: ++documentNumber })),
      questions: part.questions.map((question, questionIndex) => ({
        label: `${letter}.${questionIndex + 1}`,
        question,
        prompt: cleanQuestionPrompt(question.prompt),
        subQuestions: (question.subQuestions ?? []).map(cleanSubQuestion),
        answerLines: answerLinesFor(question),
      })),
    };
  });
}
