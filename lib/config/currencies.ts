const CURRENCY_BY_COUNTRY: Record<string, string> = Object.fromEntries(
  Object.entries(COUNTRIES_BY_CURRENCY).flatMap(([currency, countries]) =>
    countries.split(" ").map((country) => [country, currency]),
  ),
);

/** Monnaie d'un pays ; `null` si le pays est inconnu (on affiche alors le prix en FCFA). */
export function currencyForCountry(country: string | null | undefined): string | null {
  if (!country) return null;
  return CURRENCY_BY_COUNTRY[country.toUpperCase()] ?? null;
}

/** Monnaies du franc CFA (XAF et XOF valent exactement la même chose). */
export function isFcfaCurrency(currency: string | null): boolean {
  return currency === "XAF" || currency === "XOF";
}
