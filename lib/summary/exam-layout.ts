/**
 * Mise en page commune d'une épreuve — partagée par l'affichage
 * (`ExamResultPanel`), le PDF (`exam-pdf.ts`) et le texte brut (`exam-text.ts`) :
 *  - parties lettrées « PARTIE A », « PARTIE B »… ;
 *  - questions numérotées « A.1 », « A.2 »… (Vrai/Faux compris : chaque
 *    question porte ses points) ;
 *  - sous-questions « a) », « b) »… ;
 *  - documents numérotés en continu sur toute l'épreuve (« Document 1 »…) ;
 *  - intitulés du document dans la LANGUE DE L'ÉPREUVE (pas celle de
 *    l'interface) : une épreuve rédigée en anglais garde « PART A », « Duration »…
 *    même si l'application est en français.
 *
 * Client-safe (aucun `server-only`).
 */

